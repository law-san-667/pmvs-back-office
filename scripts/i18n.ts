/**
 * Messages of the site: one JSON file per area and language under
 * i18n/messages/<language>/<area>.json, French being the source.
 *
 *   bun scripts/i18n.ts          writes i18n/messages/index.ts, then checks
 *   bun scripts/i18n.ts --check  checks only (CI)
 *
 * The check fails when a language misses a text, has one French does not,
 * or changes the {placeholders} / plural forms of a text.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parse, TYPE, type MessageFormatElement } from "@formatjs/icu-messageformat-parser";

const LOCALES = ["fr", "en", "pt", "ar"] as const;
const dir = join(process.cwd(), "i18n/messages");
const checkOnly = process.argv.includes("--check");

const areas = readdirSync(join(dir, "fr"))
  .filter((name) => name.endsWith(".json"))
  .map((name) => name.slice(0, -5))
  .sort();

const ident = (area: string) => area.replace(/[^a-zA-Z0-9]+(.)/g, (_, c: string) => c.toUpperCase());

if (!checkOnly) {
  const lines = [
    "// Generated by scripts/i18n.ts: do not edit.",
    ...LOCALES.flatMap((locale) =>
      areas.map((area) => `import ${locale}_${ident(area)} from "./${locale}/${area}.json";`),
    ),
    "",
    ...LOCALES.map(
      (locale) =>
        `const ${locale} = {\n${areas.map((area) => `  ${JSON.stringify(area)}: ${locale}_${ident(area)},`).join("\n")}\n};`,
    ),
    "",
    "export type Messages = typeof fr;",
    `export const messages: Record<"fr" | "en" | "pt" | "ar", Messages> = { fr, en, pt, ar };`,
    "",
  ];
  writeFileSync(join(dir, "index.ts"), lines.join("\n"));
}

type Tree = { [key: string]: string | Tree };
const flatten = (tree: Tree, prefix = ""): Map<string, string> => {
  const out = new Map<string, string>();
  for (const [key, value] of Object.entries(tree)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof value === "string") out.set(path, value);
    else for (const [k, v] of flatten(value, path)) out.set(k, v);
  }
  return out;
};
/** The arguments of an ICU message ({name}, {count, plural, …}, <b>…</b>), or the syntax error. */
const args = (text: string) => {
  const names = new Set<string>();
  const walk = (elements: MessageFormatElement[]) => {
    for (const element of elements) {
      if (element.type === TYPE.argument || element.type === TYPE.number || element.type === TYPE.date || element.type === TYPE.time) {
        names.add(element.value);
      } else if (element.type === TYPE.plural || element.type === TYPE.select) {
        names.add(element.value);
        for (const option of Object.values(element.options)) walk(option.value);
      } else if (element.type === TYPE.tag) {
        names.add(`<${element.value}>`);
        walk(element.children);
      }
    }
  };
  try {
    walk(parse(text));
  } catch (error) {
    return `invalid ICU: ${(error as Error).message}`;
  }
  return [...names].sort().join(",");
};

const problems: string[] = [];
for (const area of areas) {
  const source = flatten(JSON.parse(readFileSync(join(dir, "fr", `${area}.json`), "utf8")));
  for (const [key, text] of source) {
    if (args(text).startsWith("invalid")) problems.push(`fr/${area}: ${key} ${args(text)}`);
  }
  for (const locale of LOCALES.slice(1)) {
    const file = join(dir, locale, `${area}.json`);
    if (!existsSync(file)) {
      problems.push(`${locale}/${area}.json is missing`);
      continue;
    }
    const target = flatten(JSON.parse(readFileSync(file, "utf8")));
    for (const [key, text] of source) {
      const value = target.get(key);
      if (value === undefined || !value.trim()) problems.push(`${locale}/${area}: missing ${key}`);
      else if (args(text) !== args(value)) problems.push(`${locale}/${area}: ${key} has {${args(value)}} instead of {${args(text)}}`);
    }
    for (const key of target.keys()) if (!source.has(key)) problems.push(`${locale}/${area}: ${key} is not in French`);
  }
}
for (const locale of LOCALES.slice(1)) {
  for (const name of readdirSync(join(dir, locale))) {
    if (name.endsWith(".json") && !areas.includes(name.slice(0, -5))) problems.push(`${locale}/${name} has no French file`);
  }
}
if (problems.length) {
  console.log(problems.join("\n"));
  console.log(`${problems.length} problem(s)`);
  process.exit(1);
}
console.log(`OK: ${areas.length} area(s), ${LOCALES.length} languages`);
